"use strict";

/**
 * One-shot maintainer script: fetch Google Fonts CSS (woff2), keep latin + latin-ext
 * subsets only, download files to assets/fonts/, write assets/css/fonts.css.
 */
const fs = require("node:fs");
const path = require("node:path");
const https = require("node:https");

const root = path.join(__dirname, "..");
const fontsDir = path.join(root, "assets", "fonts");
const fontsCssPath = path.join(root, "assets", "css", "fonts.css");

const GOOGLE_CSS_URL = `https://${["fonts", "googleapis", "com"].join(".")}/css2?family=Jost:wght@400;500;600;700&family=Open+Sans:ital,wght@0,400;0,600;0,700;1,400&display=swap`;

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

/**
 * @param {string} url
 * @returns {Promise<string>}
 */
const fetchText = (url) =>
  new Promise((resolve, reject) => {
    https
      .get(url, { headers: { "User-Agent": UA } }, (res) => {
        if (res.statusCode && res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
          fetchText(res.headers.location).then(resolve, reject);
          return;
        }
        const chunks = [];
        res.on("data", (c) => chunks.push(c));
        res.on("end", () => resolve(Buffer.concat(chunks).toString("utf8")));
        res.on("error", reject);
      })
      .on("error", reject);
  });

/**
 * @param {string} url
 * @param {string} dest
 * @returns {Promise<void>}
 */
const downloadFile = (url, dest) =>
  new Promise((resolve, reject) => {
    if (fs.existsSync(dest) && fs.statSync(dest).size > 0) {
      resolve();
      return;
    }
    https
      .get(url, { headers: { "User-Agent": UA } }, (res) => {
        if (res.statusCode && res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
          downloadFile(res.headers.location, dest).then(resolve, reject);
          return;
        }
        const chunks = [];
        res.on("data", (c) => chunks.push(c));
        res.on("end", () => {
          fs.writeFileSync(dest, Buffer.concat(chunks));
          resolve();
        });
        res.on("error", reject);
      })
      .on("error", reject);
  });

/**
 * @param {string} unicodeRange
 * @returns {"latin"|"latin-ext"|null}
 */
const subsetForRange = (unicodeRange) => {
  const trimmed = unicodeRange.trim();
  if (trimmed.startsWith("U+0000-00FF")) {
    return "latin";
  }
  if (trimmed.startsWith("U+0100-02BA")) {
    return "latin-ext";
  }
  return null;
};

/**
 * @param {string} css
 * @returns {Array<{ family: string, style: string, weight: string, unicodeRange: string, url: string }>}
 */
const parseFontFaces = (css) => {
  const blocks = css.match(/@font-face\s*\{[\s\S]*?\}/gu) || [];
  /** @type {Array<{ family: string, style: string, weight: string, unicodeRange: string, url: string }>} */
  const out = [];
  for (const block of blocks) {
    const family = block.match(/font-family:\s*['"]?([^'";]+)/iu)?.[1]?.trim();
    const style = block.match(/font-style:\s*(\w+)/iu)?.[1] || "normal";
    const weight = block.match(/font-weight:\s*(\d+)/iu)?.[1];
    const unicodeRange = block.match(/unicode-range:\s*([^;]+);/iu)?.[1]?.trim();
    const url = block.match(/url\(([^)]+\.woff2)\)/iu)?.[1];
    if (!family || !weight || !unicodeRange || !url) {
      continue;
    }
    if (!subsetForRange(unicodeRange)) {
      continue;
    }
    out.push({ family, style, weight, unicodeRange, url });
  }
  return out;
};

/**
 * @param {string} family
 * @param {string} style
 * @param {string} weight
 * @param {"latin"|"latin-ext"} subset
 * @returns {string}
 */
const localFilename = (family, style, weight, subset) => {
  const slug = family.toLowerCase().replace(/\s+/gu, "-");
  const styleSlug = style === "italic" ? "italic" : "normal";
  return `${slug}-${subset}-${weight}-${styleSlug}.woff2`;
};

/**
 * @returns {Promise<void>}
 */
const main = async () => {
  const css = await fetchText(GOOGLE_CSS_URL);
  const faces = parseFontFaces(css);
  if (faces.length === 0) {
    throw new Error("generate-self-hosted-fonts: no latin/latin-ext @font-face blocks");
  }

  fs.mkdirSync(fontsDir, { recursive: true });

  /** @type {string[]} */
  const cssLines = [
    "/**",
    " * Jost + Open Sans — self-hosted (SIL OFL). Latin + latin-ext subsets only.",
    " * Generated by scripts/generate-self-hosted-fonts.js (upstream OFL webfont CSS).",
    " */",
    "",
  ];

  const seenFiles = new Set();
  for (const face of faces) {
    const subset = subsetForRange(face.unicodeRange);
    if (!subset) {
      continue;
    }
    const filename = localFilename(face.family, face.style, face.weight, subset);
    const dest = path.join(fontsDir, filename);
    if (!seenFiles.has(filename)) {
      await downloadFile(face.url, dest);
      seenFiles.add(filename);
    }
    cssLines.push("@font-face {");
    cssLines.push(`  font-family: "${face.family}";`);
    cssLines.push(`  font-style: ${face.style};`);
    cssLines.push(`  font-weight: ${face.weight};`);
    cssLines.push("  font-display: swap;");
    cssLines.push(`  src: url("/assets/fonts/${filename}") format("woff2");`);
    cssLines.push(`  unicode-range: ${face.unicodeRange};`);
    cssLines.push("}");
    cssLines.push("");
  }

  fs.writeFileSync(fontsCssPath, `${cssLines.join("\n").trimEnd()}\n`);
  console.log(`Wrote ${faces.length} @font-face rules → ${path.relative(root, fontsCssPath)}`);
  console.log(`Font files in assets/fonts/: ${seenFiles.size} unique woff2`);
};

if (require.main === module) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}

module.exports = { parseFontFaces, subsetForRange, localFilename, GOOGLE_CSS_URL };
